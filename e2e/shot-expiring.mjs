import { createRequire } from 'node:module';
const { chromium } = createRequire(import.meta.url)('playwright');
const BASE = 'http://localhost:3000', OUT = process.argv[2];
const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium' });
const ctx = await b.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true }); const p = await ctx.newPage();
const sweep = async () => { for (let i = 0; i < 4; i++) { for (const s of ['.lv-opt', '.tip-ok', 'button:has-text("Maybe later")']) if (await p.locator(s).count()) await p.locator(s).first().click({ timeout: 1500 }).catch(() => {}); await p.waitForTimeout(120); } };
const ok = (n, v) => console.log(v ? 'PASS' : 'FAIL', n);
const sql = (q) => fetch('http://localhost:54321/__e2e/sql?q=' + encodeURIComponent(q)).then((r) => r.text());
await p.goto(`${BASE}/login`); await p.getByRole('radio', { name: 'Accept' }).click(); await p.getByRole('button', { name: 'Start playing' }).click(); await p.waitForURL('**/cook');
await p.waitForTimeout(1500); await sweep();
const U = '(select id from public.profiles order by created_at desc limit 1)';
const items = [['Avocado', 1], ['Romaine lettuce', 0], ['Milk', 2], ['Chicken breast', 3], ['Eggs', 30], ['Flour', 60], ['Rice', 90], ['Onion', 20]];
for (const [n, d] of items) await sql(`insert into public.pantry_items (user_id, name, category, expires_on) values (${U}, '${n}', 'Produce', current_date + ${d})`);
await p.reload(); await p.waitForTimeout(2000); await sweep();
await p.locator('.nav a[href="/home"]').click({ force: true }); await p.waitForURL('**/home'); await p.waitForTimeout(3500); await sweep();
const heads = async () => p.evaluate(() => [...document.querySelectorAll('.rcard')].slice(0, 10).map((c) => ({ t: c.querySelector('h2')?.textContent, soon: !!c.querySelector('.chip.soon'), chip: c.querySelector('.chip.soon')?.textContent || '' })));
const a = await heads();
console.log(JSON.stringify(a.slice(0, 9)));
let nSoon = 0; while (nSoon < a.length && a[nSoon].soon) nSoon++;
ok(`expiring block on top (${nSoon} dishes)`, nSoon >= 2 && nSoon <= 8 && a.slice(0, nSoon).every((x) => x.soon));
ok('nothing expiring below the block in the first 10 is forced up', a.slice(nSoon).filter((x) => x.soon).length >= 0);
ok('heading + plain-words nudge', (await p.getByTestId('soon-note').innerText()).includes('about to go bad'));
console.log((await p.getByTestId('soon-note').innerText()));
await p.screenshot({ path: `${OUT}/exp-home.png` });
await p.getByTestId('shuffle').click(); await p.waitForTimeout(1500);
const bb = await heads();
ok('shuffle keeps the same expiring block on top', JSON.stringify(bb.slice(0, nSoon).map((x) => x.t)) === JSON.stringify(a.slice(0, nSoon).map((x) => x.t)));
ok('shuffle changes what is below', JSON.stringify(bb.slice(nSoon).map((x) => x.t)) !== JSON.stringify(a.slice(nSoon).map((x) => x.t)));
// pull to refresh is off on Home
await p.evaluate(() => window.scrollTo(0, 0));
const y0 = await p.evaluate(() => document.querySelector('.ptr')?.getBoundingClientRect().height ?? 0);
const cdp = await ctx.newCDPSession(p);
await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x: 200, y: 200 }] });
for (let i = 1; i <= 10; i++) await cdp.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x: 200, y: 200 + i * 20 }] });
await p.waitForTimeout(200);
const y1 = await p.evaluate(() => document.querySelector('.ptr')?.getBoundingClientRect().height ?? 0);
await cdp.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] });
ok('no pull-down refresh indicator on Home', y1 === 0 || y1 === y0);
// one-line buttons on Cook
await p.locator('.nav a[href="/cook"]').click({ force: true }); await p.waitForURL('**/cook'); await p.waitForTimeout(1500); await sweep();
const hs = await p.evaluate(() => [...document.querySelectorAll('.uw-chip')].map((e) => e.getBoundingClientRect().height));
ok('Cook buttons are one line tall', hs.length === 2 && hs.every((h) => h < 46));
await p.locator('.uw-chip').first().scrollIntoViewIfNeeded(); await p.screenshot({ path: `${OUT}/exp-cook.png` });
await b.close();
