import { createRequire } from 'node:module';
const { chromium } = createRequire(import.meta.url)('playwright');
const BASE = 'http://localhost:3000', OUT = process.argv[2];
const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium' });
const ctx = await b.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true }); const p = await ctx.newPage();
const sweep = async () => { for (let i = 0; i < 4; i++) { for (const sel of ['.tip-ok', 'button:has-text("Maybe later")']) { if (await p.locator(sel).count()) await p.locator(sel).first().click({ timeout: 1500 }).catch(() => {}); } await p.waitForTimeout(150); } };
const ok = (n, v) => console.log(v ? 'PASS' : 'FAIL', n);
await p.goto(`${BASE}/login`); await p.getByRole('radio', { name: 'Accept' }).click(); await p.getByRole('button', { name: 'Start playing' }).click(); await p.waitForURL('**/cook');
await fetch('http://localhost:54321/__e2e/sql?q=' + encodeURIComponent('delete from public.pantry_items')).then((r) => r.text());
await p.reload(); await p.waitForTimeout(2500); await sweep();
ok('cook shows the question', await p.getByTestId('fr-question').count() === 1);
ok('hero + 2 minis', await p.locator('.fr-hero').count() === 1 && await p.locator('.fr-mini').count() === 2);
const h1 = await p.locator('.fr-in h2').innerText(); await p.getByTestId('shuffle-pick').click(); await p.waitForTimeout(300); ok('shuffle changes the pick', (await p.locator('.fr-in h2').innerText()) !== h1);
await p.getByTestId('cook-pick').click(); await p.waitForTimeout(800); ok('recipe opens', await p.locator('[role=dialog], .sheet').count() > 0); await p.screenshot({ path: OUT + '/fr-recipe.png' }); await p.keyboard.press('Escape'); await p.reload(); await p.waitForTimeout(2000); await sweep();
ok('no filters yet', await p.locator('.cook-filters').count() === 0);
await p.screenshot({ path: `${OUT}/fr-cook.png` });
await p.getByTestId('use-what-i-have').click(); await p.waitForURL('**/pantry'); await p.waitForTimeout(1500); await sweep();
ok('empty pantry shows the basket', await p.getByTestId('pantry-empty').count() === 1);
ok('form folded away', await p.locator('.addform').count() === 0);
await p.screenshot({ path: `${OUT}/fr-pantry.png` });
await p.getByTestId('start-basics').click(); await p.waitForTimeout(1800);
ok('10 basics added', await p.getByTestId('pantry-empty').count() === 0);
await p.screenshot({ path: `${OUT}/fr-pantry-after.png` });
await p.locator('.nav a[href="/cook"]').click({ force: true }); await p.waitForTimeout(2000); await sweep();
await p.getByTestId('use-what-i-have').click(); await p.waitForTimeout(1500);
console.log('results:', (await p.locator('.eyebrow').allTextContents()).join(' | ').slice(0, 200));
await p.screenshot({ path: `${OUT}/fr-cook-after.png` });
await b.close();
