import { createRequire } from 'node:module';
const { chromium } = createRequire(import.meta.url)('playwright');
const BASE = 'http://localhost:3000', OUT = process.argv[2];
const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium' });
const ctx = await b.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true }); const p = await ctx.newPage();
const sweep = async () => { for (let i = 0; i < 4; i++) { for (const sel of ['.tip-ok', 'button:has-text("Maybe later")', '.popup-scrim button:has-text("Close")', '.popup-scrim button:has-text("Leave")', '.popup-scrim button']) { if (await p.locator(sel).count()) await p.locator(sel).first().click({ timeout: 1500 }).catch(() => {}); } await p.waitForTimeout(150); } };
const ok = (n, v) => console.log(v ? 'PASS' : 'FAIL', n);
await p.goto(`${BASE}/login`); await p.getByRole('radio', { name: 'Accept' }).click(); await p.getByRole('button', { name: 'Start playing' }).click(); await p.waitForURL('**/cook');
await p.waitForTimeout(1500); await sweep();
await p.getByRole('button', { name: /let.s cook it/i }).first().click(); await p.waitForTimeout(800);
await p.getByRole('button', { name: /i cooked it/i }).first().click(); await p.waitForTimeout(600);
ok('Write my recipe button shown, editor hidden', await p.getByTestId('lm-write').count() === 1 && await p.getByTestId('lm-editor').count() === 0);
await p.screenshot({ path: `${OUT}/lr-1.png` });
await p.getByTestId('lm-write').click(); await p.waitForTimeout(500);
ok('editor opens', await p.getByTestId('lm-editor').count() === 1);
await p.getByTestId('lm-paste').fill('Ingredients\n2 eggs\n1 cup rice\nDirections\n1. Cook the rice.\n2. Fry with eggs.');
await p.getByTestId('lm-split').click(); await p.waitForTimeout(300);
ok('split fills ingredients', (await p.getByTestId('lm-ings').inputValue()).includes('2 eggs'));
ok('split fills steps', (await p.getByTestId('lm-steps').inputValue()).includes('Fry with eggs'));
await p.screenshot({ path: `${OUT}/lr-2.png` });
await p.locator('input[type=file]').last().setInputFiles('/tmp/plate.jpg'); await p.waitForTimeout(500);
await p.getByRole('button', { name: 'Submit' }).click(); await p.waitForTimeout(2500); await sweep();
await sweep(); await p.waitForTimeout(800); await sweep(); await p.getByTestId('saved-chip').click(); await p.waitForTimeout(800);
ok('recipe saved under Yours', await p.getByTestId('mine-item').count() === 1);
await p.goBack().catch(()=>{}); 
await b.close();
