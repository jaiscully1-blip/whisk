import { createRequire } from 'node:module';
const { chromium } = createRequire(import.meta.url)('playwright');
const BASE = 'http://localhost:3000', OUT = process.argv[2];
const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium' });
const ctx = await b.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true }); const p = await ctx.newPage();
const sweep = async () => { for (let i = 0; i < 4; i++) { for (const sel of ['.lv-opt', '.tip-ok', 'button:has-text("Maybe later")']) { if (await p.locator(sel).count()) await p.locator(sel).first().click({ timeout: 1500 }).catch(() => {}); } await p.waitForTimeout(150); } };
const ok = (n, v) => console.log(v ? 'PASS' : 'FAIL', n);
await p.goto(`${BASE}/login`); await p.getByRole('radio', { name: 'Accept' }).click(); await p.getByRole('button', { name: 'Start playing' }).click(); await p.waitForURL('**/cook');
await p.waitForTimeout(1500); await sweep();
await p.locator('#o-dish').first().fill('Greece'); await p.locator('button.cs-go').click();
await p.waitForSelector('.dflip', { timeout: 15000 }); await p.waitForTimeout(500);
const rows = p.locator('.dflip button.dish-row'); const n = await rows.count();
await rows.nth(Math.min(5, n - 1)).scrollIntoViewIfNeeded(); await p.waitForTimeout(300);
await rows.nth(Math.min(5, n - 1)).click(); await p.waitForTimeout(400);
await p.screenshot({ path: `${OUT}/rv-mid.png` });
await p.waitForTimeout(1800);
const m = await p.evaluate(() => { const c = document.querySelector('.dflip.on'); const r = c.getBoundingClientRect(); return { top: r.top, bottom: r.bottom, hud: document.querySelector('.hud').getBoundingClientRect().bottom, nav: document.querySelector('.nav').getBoundingClientRect().top, h: r.height }; });
console.log(JSON.stringify(m));
ok('card top clears the top bar', m.top >= m.hud - 2);
ok('card bottom clears the tab bar (or it is taller than the room)', m.bottom <= m.nav + 2 || m.h > m.nav - m.hud);
await p.screenshot({ path: `${OUT}/rv-end.png` });
await b.close();
