import { createRequire } from 'node:module';
const { chromium } = createRequire(import.meta.url)('playwright');
const BASE = 'http://localhost:3000';
const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium' });
const p = await (await b.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true })).newPage();
const sweep = async () => { for (let i = 0; i < 4; i++) { for (const sel of ['.tip-ok', 'button:has-text("Maybe later")', '.popup-scrim button']) { if (await p.locator(sel).count()) await p.locator(sel).first().click({ timeout: 1500 }).catch(() => {}); } await p.waitForTimeout(150); } };
const ok = (n, v) => console.log(v ? 'PASS' : 'FAIL', n);
const sql = (q) => fetch('http://localhost:54321/__e2e/sql?q=' + encodeURIComponent(q)).then((r) => r.text());
await p.goto(`${BASE}/login`); await p.getByRole('radio', { name: 'Accept' }).click(); await p.getByRole('button', { name: 'Start playing' }).click(); await p.waitForURL('**/cook'); await p.waitForTimeout(2000); await sweep();
await sql("insert into public.saved_recipes (user_id, recipe_id) select id, 'w-in-falooda' from public.profiles order by created_at desc limit 1");
await p.reload(); await p.waitForTimeout(2500); await sweep();
await p.getByTestId('saved-chip').click(); await p.waitForTimeout(1200);
ok('saved box shown', await p.getByTestId('saved-box').count() === 1);
ok('no filters card', await p.locator('.cook-filters').count() === 0);
ok('no results list', (await p.locator('main').innerText()).includes('recipe you can make') === false);
ok('Falooda listed', (await p.locator('main').innerText()).includes('Falooda'));
await p.getByTestId('back-to-picks').click(); await p.waitForTimeout(600);
await p.getByTestId('use-what-i-have').click(); await p.waitForTimeout(1500);
ok('pantry view has no saved box', await p.getByTestId('saved-box').count() === 0);
ok('pantry view has filters', await p.locator('.cook-filters').count() === 1);
await b.close();
