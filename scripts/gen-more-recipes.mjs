// Generates supabase/migrations/0026_more_recipes.sql from lib/recipes/more.json.
// Every recipe there was collected from a real web page (its url); steps are short summaries.
import fs from 'node:fs';
import { canon, difficulty } from '../lib/recipes/match.js';

const recipes = JSON.parse(fs.readFileSync(new URL('../lib/recipes/more.json', import.meta.url), 'utf8'));
const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const arr = (a) => `array[${a.map(q).join(', ')}]::text[]`;
const rows = recipes.map((r) => {
  if (!/^https:\/\//.test(r.url)) throw new Error('bad url ' + r.url);
  const data = { ...r }; delete data.id;
  return `(${q(r.id)}, ${q(r.title)}, ${q(r.cuisine)}, ${q(r.source)}, ${q(r.url)}, ${r.minutes}, ${r.servings}, ${r.technique}, ${r.prep}, ${r.precision}, ${r.steps.length}, ${difficulty(r)}, ${arr([...new Set(r.key.map(canon))])}, ${q(JSON.stringify(data))}::jsonb)`;
});
const sql = `-- Generated by scripts/gen-more-recipes.mjs from lib/recipes/more.json. Do not edit by hand.
-- ${recipes.length} real recipes, each linking to the page it came from.
insert into public.web_recipes (id, title, cuisine, source, url, minutes, servings, technique, prep, precision_level, step_count, score, key_canon, data) values
${rows.join(',\n')}
on conflict (id) do update set title = excluded.title, cuisine = excluded.cuisine, source = excluded.source, url = excluded.url, minutes = excluded.minutes,
  servings = excluded.servings, technique = excluded.technique, prep = excluded.prep, precision_level = excluded.precision_level, step_count = excluded.step_count,
  score = excluded.score, key_canon = excluded.key_canon, data = excluded.data, active = true;
`;
fs.writeFileSync(new URL('../supabase/migrations/0026_more_recipes.sql', import.meta.url), sql);
console.log(`wrote ${recipes.length} recipes`);
